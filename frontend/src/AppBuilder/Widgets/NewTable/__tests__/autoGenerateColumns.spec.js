import autogenerateColumns from '../_utils/autoGenerateColumns';

const dynamic = (columnData) => autogenerateColumns({}, [], [], true, columnData, false);

describe('autogenerateColumns with dynamic columns', () => {
  it('generates every named column', () => {
    const columns = dynamic([
      { name: 'Name', key: 'name' },
      { name: 'email', columnType: 'string' },
    ]);

    expect(columns.map(({ name, key, autogenerated }) => ({ name, key, autogenerated }))).toEqual([
      { name: 'Name', key: 'name', autogenerated: true },
      { name: 'email', key: 'email', autogenerated: true },
    ]);
  });

  it('keeps the named columns when the first entry is empty', () => {
    const columns = dynamic([{}, { name: 'Name', key: 'name' }, null, { name: 'Age', key: 'age' }]);

    expect(columns.map((column) => column.key)).toEqual(['name', 'age']);
  });

  it('keeps the id given in the column data', () => {
    expect(dynamic([{ id: 'col-1', name: 'Name' }])[0].id).toEqual('col-1');
  });

  it('returns no columns for missing or non-array column data', () => {
    expect(dynamic([])).toEqual([]);
    expect(dynamic(undefined)).toEqual([]);
    expect(dynamic('name,email')).toEqual([]);
  });
});
